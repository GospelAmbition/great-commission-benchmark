"""
Bundle compiler for CLI distribution.

Compiles JSON exports into Python bundles for embedding in gcb-runner.
"""

import base64
import gzip
import hashlib
import json
from datetime import datetime
from pathlib import Path
from typing import Optional


def compile_bundle(
    json_path: Path,
    output_dir: Path,
    version_slug: Optional[str] = None,
) -> tuple[Path, dict]:
    """
    Compile a JSON export into a Python bundle.
    
    Args:
        json_path: Path to the JSON export file
        output_dir: Directory to write bundle files
        version_slug: Optional version slug (e.g., "v1_0"). Derived from version if not provided.
        
    Returns:
        Tuple of (output_dir, stats)
    """
    # Load JSON
    with open(json_path, "r") as f:
        data = json.load(f)
    
    version = data.get("benchmark_version", "unknown")
    
    # Generate version slug if not provided
    if version_slug is None:
        version_slug = "v" + version.replace(".", "_")
    
    # Compress the data
    json_bytes = json.dumps(data).encode("utf-8")
    original_size = len(json_bytes)
    
    compressed = gzip.compress(json_bytes, compresslevel=9)
    compressed_size = len(compressed)
    
    # Base64 encode
    encoded = base64.b64encode(compressed).decode("ascii")
    
    # Generate checksum
    checksum = hashlib.sha256(json_bytes).hexdigest()
    
    # Create output directory
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Generate __init__.py
    init_content = f'''"""
GCB Benchmark Version {version}

This module provides the benchmark questions for version {version}.
Do not edit - this file is auto-generated.
"""

from .bundle import VERSION, QUESTION_COUNT, TIER_DISTRIBUTION, load_questions

__all__ = ["VERSION", "QUESTION_COUNT", "TIER_DISTRIBUTION", "load_questions"]
'''
    
    # Generate bundle.py
    tier_distribution = data.get("metadata", {}).get("tier_counts", {})
    question_count = data.get("metadata", {}).get("total_questions", len(data.get("questions", [])))
    
    bundle_content = f'''"""
GCB Benchmark Bundle v{version}

Auto-generated bundle for CLI distribution.
Do not edit this file directly.

Generated: {datetime.utcnow().isoformat()}
"""

import base64
import gzip
import json

VERSION = "{version}"
RELEASE_DATE = "{datetime.utcnow().strftime('%Y-%m-%d')}"
QUESTION_COUNT = {question_count}
TIER_DISTRIBUTION = {tier_distribution}
CHECKSUM = "sha256:{checksum}"

# Compressed + base64 encoded question data
_BUNDLE_DATA = """
{_format_base64(encoded)}
"""


def _decode_bundle() -> dict:
    """Decode the bundle data. Internal use only."""
    compressed = base64.b64decode(_BUNDLE_DATA.strip())
    json_bytes = gzip.decompress(compressed)
    return json.loads(json_bytes.decode("utf-8"))


def load_questions() -> list[dict]:
    """Load all questions from the bundle."""
    data = _decode_bundle()
    return data.get("questions", [])


def load_judge_prompts() -> dict[str, str]:
    """Load judge prompt templates from the bundle."""
    data = _decode_bundle()
    return data.get("judge_prompts", {{}})


def load_scoring_config() -> dict:
    """Load scoring configuration from the bundle."""
    data = _decode_bundle()
    return data.get("scoring", {{}})


def get_metadata() -> dict:
    """Get bundle metadata."""
    data = _decode_bundle()
    return data.get("metadata", {{}})


def verify_checksum() -> bool:
    """Verify the bundle checksum."""
    import hashlib
    data = _decode_bundle()
    json_bytes = json.dumps(data).encode("utf-8")
    actual = "sha256:" + hashlib.sha256(json_bytes).hexdigest()
    return actual == CHECKSUM
'''
    
    # Write files
    init_path = output_dir / "__init__.py"
    bundle_path = output_dir / "bundle.py"
    
    with open(init_path, "w") as f:
        f.write(init_content)
    
    with open(bundle_path, "w") as f:
        f.write(bundle_content)
    
    # Return stats
    stats = {
        "version": version,
        "version_slug": version_slug,
        "original_size": original_size,
        "compressed_size": compressed_size,
        "compression_ratio": round((1 - compressed_size / original_size) * 100, 1),
        "question_count": question_count,
        "checksum": f"sha256:{checksum}",
        "files": [str(init_path), str(bundle_path)],
    }
    
    return output_dir, stats


def _format_base64(data: str, line_width: int = 76) -> str:
    """Format base64 string with line breaks."""
    lines = []
    for i in range(0, len(data), line_width):
        lines.append(data[i:i + line_width])
    return "\n".join(lines)


def compile_from_version(
    version_id: int,
    output_dir: Path,
) -> tuple[Path, dict]:
    """
    Compile a bundle directly from a version ID.
    
    First exports to JSON, then compiles to bundle.
    
    Args:
        version_id: Version ID to compile
        output_dir: Directory to write bundle files
        
    Returns:
        Tuple of (output_dir, stats)
    """
    from gcb_builder.export.question_export import export_version_to_json
    from gcb_builder.versioning.builder import VersionBuilder
    
    # Get version info
    builder = VersionBuilder()
    version = builder.get_version(version_id)
    
    if not version:
        raise ValueError(f"Version {version_id} not found")
    
    # Export to temp JSON
    import tempfile
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as f:
        temp_path = Path(f.name)
    
    try:
        json_path = export_version_to_json(version_id, temp_path)
        version_slug = "v" + version.version.replace(".", "_")
        return compile_bundle(json_path, output_dir / version_slug, version_slug)
    finally:
        if temp_path.exists():
            temp_path.unlink()
